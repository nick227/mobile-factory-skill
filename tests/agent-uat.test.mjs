// Agent User Acceptance Testing (UAT) Benchmark
// Measures screen quality, functional correctness, archetype reuse, and handwritten code across
// the three example applications (Pantry Pal, Botanical Vitality, Apex Wealth).
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import * as asm from '../factory-v1/assembler.mjs';
import * as cat from '../factory-v1/catalog-contract.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const apps = ['pantry', 'fitness', 'finance'];

function loadSpec(name) {
  const file = path.join(root, `packages/assembly/examples/${name}.spec.json`);
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

test('UAT 1: Zero handwritten screen JSX across all three applications', () => {
  const metrics = { totalRoutes: 0, handwrittenLines: 0, filesChecked: [] };

  for (const name of apps) {
    const spec = loadSpec(name);
    const files = asm.emit(spec);

    for (const [filePath, content] of Object.entries(files)) {
      if (filePath.startsWith('app/') && filePath !== 'app/_layout.tsx') {
        metrics.totalRoutes++;
        metrics.filesChecked.push(filePath);

        // Verify standard generated marker is present
        assert.ok(content.includes('GENERATED by the mobile factory (assemble)'));
        // Verify only exactly ONE component element exists (<MonadPage ... />)
        const elementMatches = content.match(/<MonadPage\s+app=\{app\}\s+page="[^"]+"\s+store=\{store\}\s*\/>/g);
        assert.ok(elementMatches && elementMatches.length === 1, `${filePath} contains extraneous or custom JSX`);
        
        // Count non-boilerplate lines
        const nonGeneratedLines = content.split('\n').filter((l) => l.trim().length > 0 && !l.startsWith('//') && !l.startsWith('import') && !l.startsWith('export default function') && !l.includes('<MonadPage') && !l.includes('}'));
        metrics.handwrittenLines += nonGeneratedLines.length;
      }
    }
  }

  assert.equal(metrics.handwrittenLines, 0, 'Handwritten application JSX must be exactly 0 lines');
  assert.ok(metrics.totalRoutes >= 10, `Expected at least 10 routes across 3 apps, found ${metrics.totalRoutes}`);
});

test('UAT 2: Archetype reuse and distribution across the design space', () => {
  const archetypeUsage = new Map();
  for (const a of asm.ARCHETYPES) archetypeUsage.set(a, 0);

  let totalPages = 0;
  for (const name of apps) {
    const spec = loadSpec(name);
    for (const page of Object.values(spec.pages)) {
      totalPages++;
      if (page.archetype) {
        archetypeUsage.set(page.archetype, (archetypeUsage.get(page.archetype) ?? 0) + 1);
      }
    }
  }

  // Verify that all 6 archetypes are covered and exercised in the examples
  for (const [archetype, count] of archetypeUsage.entries()) {
    assert.ok(count >= 1, `Archetype '${archetype}' should be exercised in the test fixtures (count: ${count})`);
  }
});

